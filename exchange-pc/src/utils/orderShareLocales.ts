export function shareLanguage(locale: string): string {
  const tag = locale.trim().replace(/_/g, "-").toLowerCase()
  if (tag === "zh" || tag.startsWith("zh-")) return "zh-TW"
  const language = tag.split("-")[0]!
  return Object.prototype.hasOwnProperty.call(posterLocales, language) ? language : "en"
}
